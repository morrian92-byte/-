    // 获取某县下的乡镇/街道列表（动态生成模板）
    getTowns(countyName) {
        const isDistrict = countyName.endsWith('区');
        if (isDistrict) {
            return [
                countyName.replace('区','') + '路街道',
                countyName.replace('区','') + '桥街道',
                countyName.replace('区','') + '园街道',
                countyName.replace('区','') + '新街道',
                countyName.replace('区','') + '南街道',
            ];
        }
        return [
            countyName + '镇',
            countyName.replace('县','') + '北镇',
            countyName.replace('县','') + '南镇',
            countyName.replace('县','') + '东乡',
            countyName.replace('县','') + '西乡',
        ];
    },

    // 获取某市下的区县列表
    getCounties(cityKey, provinceKey) {
        const prov = this.provinces[provinceKey];
        if (!prov) return [];
        if (provinceKey === '京州市') return prov.districts.map(d => d + '区');

        const city = prov.cities[cityKey];
        if (!city) return [];
        return [...(city.districts || []), ...(city.counties || [])];
    },

    // 构建完整层级地址
    buildAddress(province, city, county, town) {
        return province + city + county + town;
    },
